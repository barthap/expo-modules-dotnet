import * as path from 'path';

import type { DotnetLinkingManifest, DotnetProjectRef } from '../types';
import { writeIfChangedSync } from './writeIfChanged';

const csharpBanner = '// Automatically generated by expo-modules-dotnet-autolinking. Do not edit.';
const xmlBanner = '<!-- Automatically generated by expo-modules-dotnet-autolinking. Do not edit. -->';

export interface GenerateOptions {
  outputDir: string;
  adapterPackageRoot: string;
}

export interface GenerateResult {
  writtenFiles: string[];
  skippedFiles: string[];
}

export function generateAggregator(
  manifest: DotnetLinkingManifest,
  options: GenerateOptions
): GenerateResult {
  const projects = manifest.modules.flatMap((module) => module.projects);
  const files = [
    {
      fileName: 'ExpoDotnetHost.csproj',
      content: generateCsproj(projects, options),
    },
    {
      fileName: 'LinkedExpoModulesProvider.g.cs',
      content: generateLinkedProvider(projects),
    },
    {
      fileName: 'EntryPoints.g.cs',
      content: generateEntryPoints(),
    },
  ];
  const result: GenerateResult = { writtenFiles: [], skippedFiles: [] };

  for (const file of files) {
    const filePath = path.join(options.outputDir, file.fileName);
    if (writeIfChangedSync(filePath, file.content)) {
      result.writtenFiles.push(filePath);
    } else {
      result.skippedFiles.push(filePath);
    }
  }

  return result;
}

function generateCsproj(projects: DotnetProjectRef[], options: GenerateOptions): string {
  const coreReferences = [
    path.join(options.adapterPackageRoot, 'managed/packages/Expo.JSI/Expo.JSI.csproj'),
    path.join(
      options.adapterPackageRoot,
      'managed/packages/Expo.ModulesCore/Expo.ModulesCore.csproj'
    ),
  ];
  const projectReferences = [...coreReferences, ...projects.map((project) => project.csprojPath)]
    .map((target) => relativePath(options.outputDir, target))
    .map((target) => `    <ProjectReference Include="${escapeXmlAttribute(target)}" />`)
    .join('\n');

  return `${xmlBanner}
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net10.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <GenerateRuntimeConfigurationFiles>true</GenerateRuntimeConfigurationFiles>
    <AssemblyName>ExpoDotnetHost</AssemblyName>
    <RootNamespace>Expo.ModulesCore.Generated</RootNamespace>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
  </PropertyGroup>
  <PropertyGroup Condition="'$(PublishAot)' == 'true'">
    <NativeLib>Shared</NativeLib>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="LinkedExpoModulesProvider.g.cs" />
    <Compile Include="EntryPoints.g.cs" />
  </ItemGroup>
  <ItemGroup>
${projectReferences}
  </ItemGroup>
</Project>
`;
}

// Mirrors SanitizeIdentifier in Expo.ModulesCore.Generator/ExpoModulesGenerator.cs —
// the Roslyn generator derives the provider type name from the assembly name the same way.
function sanitizeIdentifier(value: string): string {
  const sanitized = value.replace(/[^\p{L}\p{Nd}]/gu, '_');
  return sanitized.length === 0 ? 'ExpoModules' : sanitized;
}

function generateLinkedProvider(projects: DotnetProjectRef[]): string {
  const registrations = projects
    .map(
      (project) =>
        `        Expo.ModulesCore.Generated.ExpoModulesProvider_${sanitizeIdentifier(project.assemblyName)}.Register(context);`
    )
    .join('\n');
  const body = registrations.length > 0 ? `${registrations}\n` : '';

  return `${csharpBanner}
using Expo.ModulesCore;

namespace Expo.ModulesCore.Generated;

public static class LinkedExpoModulesProvider
{
    public static void Register(DotnetRuntimeContext context)
    {
${body}    }
}
`;
}

function generateEntryPoints(): string {
  return `${csharpBanner}
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using Expo.JSI;
using Expo.ModulesCore;

namespace Expo.ModulesCore.Generated;

public static class EntryPoints
{
    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_create_runtime_context",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static nint CreateRuntimeContext(nint api, nint runtimeHandle)
    {
        try
        {
            return CreateRuntimeContextCore(api, runtimeHandle);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine(ex);
            return 0;
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_teardown_runtime_context",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static void TeardownRuntimeContext(nint runtimeContext)
    {
        TeardownRuntimeContextCore(runtimeContext);
    }

    private static nint CreateRuntimeContextCore(nint api, nint runtimeHandle)
    {
        var runtime = JavaScriptRuntime.FromNative(api, runtimeHandle);
        var context = new DotnetRuntimeContext(runtime);
        try
        {
            LinkedExpoModulesProvider.Register(context);
            return GCHandle.ToIntPtr(GCHandle.Alloc(context));
        }
        catch
        {
            context.Dispose();
            throw;
        }
    }

    private static void TeardownRuntimeContextCore(nint runtimeContext)
    {
        if (runtimeContext == 0)
        {
            return;
        }

        var handle = GCHandle.FromIntPtr(runtimeContext);
        if (handle.Target is DotnetRuntimeContext context)
        {
            context.Dispose();
        }

        handle.Free();
    }
}
`;
}

function relativePath(from: string, to: string): string {
  return path.relative(from, to).split(path.sep).join('/');
}

function escapeXmlAttribute(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}
