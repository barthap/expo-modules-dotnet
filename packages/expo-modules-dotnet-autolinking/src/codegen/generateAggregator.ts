import * as path from 'path';

import type { DotnetLinkingManifest, DotnetProjectRef } from '../types';
import { writeIfChangedSync } from './writeIfChanged';

const csharpBanner = `// Automatically generated by expo-modules-dotnet-autolinking. Do not edit.
#nullable enable`;
const xmlBanner = '<!-- Automatically generated by expo-modules-dotnet-autolinking. Do not edit. -->';

export interface GenerateOptions {
  outputDir: string;
  adapterPackageRoot: string;
  platform?: string;
}

export interface GenerateResult {
  writtenFiles: string[];
  skippedFiles: string[];
}

export function generateAggregator(
  manifest: DotnetLinkingManifest,
  options: GenerateOptions
): GenerateResult {
  const projects = manifest.modules.flatMap((module) => module.projects);
  const files = [
    {
      fileName: 'ExpoDotnetHost.csproj',
      content: generateCsproj(projects, options),
    },
    {
      fileName: 'LinkedExpoModulesProvider.g.cs',
      content: generateLinkedProvider(projects),
    },
    {
      fileName: 'EntryPoints.g.cs',
      content: generateEntryPoints(options),
    },
  ];
  const result: GenerateResult = { writtenFiles: [], skippedFiles: [] };

  for (const file of files) {
    const filePath = path.join(options.outputDir, file.fileName);
    if (writeIfChangedSync(filePath, file.content)) {
      result.writtenFiles.push(filePath);
    } else {
      result.skippedFiles.push(filePath);
    }
  }

  return result;
}

function generateCsproj(projects: DotnetProjectRef[], options: GenerateOptions): string {
  const isWindows = options.platform === 'windows';
  const targetFramework = isWindows ? 'net10.0-windows10.0.19041.0' : 'net10.0';
  const coreReferences = [
    path.join(options.adapterPackageRoot, 'managed/packages/Expo.JSI/Expo.JSI.csproj'),
    path.join(
      options.adapterPackageRoot,
      'managed/packages/Expo.ModulesCore/Expo.ModulesCore.csproj'
    ),
    ...(isWindows
      ? [
          path.join(
            options.adapterPackageRoot,
            '..',
            'expo-modules-dotnet-windows',
            'managed/Expo.ModulesCore.Windows/Expo.ModulesCore.Windows.csproj'
          ),
        ]
      : []),
  ];
  const projectReferences = [...coreReferences, ...projects.map((project) => project.csprojPath)]
    .map((target) => relativePath(options.outputDir, target))
    .map((target) => `    <ProjectReference Include="${escapeXmlAttribute(target)}" />`)
    .join('\n');

  return `${xmlBanner}
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>${targetFramework}</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <GenerateRuntimeConfigurationFiles>true</GenerateRuntimeConfigurationFiles>
    <AssemblyName>ExpoDotnetHost</AssemblyName>
    <RootNamespace>Expo.ModulesCore.Generated</RootNamespace>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    ${isWindows ? '<CopyLocalLockFileAssemblies>true</CopyLocalLockFileAssemblies>' : ''}
  </PropertyGroup>
  <PropertyGroup Condition="'$(PublishAot)' == 'true'">
    <NativeLib>Shared</NativeLib>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="LinkedExpoModulesProvider.g.cs" />
    <Compile Include="EntryPoints.g.cs" />
  </ItemGroup>
  <ItemGroup>
${projectReferences}
  </ItemGroup>
</Project>
`;
}

// Mirrors SanitizeIdentifier in Expo.ModulesCore.Generator/ExpoModulesGenerator.cs —
// the Roslyn generator derives the provider type name from the assembly name the same way.
function sanitizeIdentifier(value: string): string {
  const sanitized = value.replace(/[^\p{L}\p{Nd}]/gu, '_');
  return sanitized.length === 0 ? 'ExpoModules' : sanitized;
}

function generateLinkedProvider(projects: DotnetProjectRef[]): string {
  const registrations = projects
    .map(
      (project) =>
        `        Expo.ModulesCore.Generated.ExpoModulesProvider_${sanitizeIdentifier(project.assemblyName)}.Register(context);`
    )
    .join('\n');
  const body = registrations.length > 0 ? `${registrations}\n` : '';
  const viewDefinitionRegistrations = projects
    .map(
      (project) =>
        `        views.AddRange(Expo.ModulesCore.Generated.ExpoModulesProvider_${sanitizeIdentifier(project.assemblyName)}.GetViewDefinitions());`
    )
    .join('\n');
  const viewDefinitionBody =
    viewDefinitionRegistrations.length > 0 ? `${viewDefinitionRegistrations}\n` : '';
  const createViewCases = projects
    .map((project) => {
      const provider = `Expo.ModulesCore.Generated.ExpoModulesProvider_${sanitizeIdentifier(project.assemblyName)}`;
      return `        if (HasView(${provider}.GetViewDefinitions(), componentName))
        {
            return ${provider}.CreateView(context, componentName);
        }`;
    })
    .join('\n');
  const updateViewCases = projects
    .map((project) => {
      const provider = `Expo.ModulesCore.Generated.ExpoModulesProvider_${sanitizeIdentifier(project.assemblyName)}`;
      return `        if (HasView(${provider}.GetViewDefinitions(), componentName))
        {
            ${provider}.UpdateViewProp(context, componentName, view, propName, value);
            return;
        }`;
    })
    .join('\n');

  return `${csharpBanner}
using System.Collections.Generic;
using System.Linq;
using Expo.ModulesCore;

namespace Expo.ModulesCore.Generated;

public static class LinkedExpoModulesProvider
{
    public static void Register(DotnetRuntimeContext context)
    {
${body}    }

    public static IReadOnlyList<GeneratedViewDefinition> GetViewDefinitions()
    {
        var views = new List<GeneratedViewDefinition>();
${viewDefinitionBody}        ValidateUniqueViewComponentNames(views);
        return views;
    }

    public static object CreateView(DotnetRuntimeContext context, string componentName)
    {
        _ = GetViewDefinitions();
${createViewCases}
        throw new InvalidOperationException($"Unknown Expo view component '{componentName}'.");
    }

    public static void UpdateViewProp(
        DotnetRuntimeContext context,
        string componentName,
        object view,
        string propName,
        string? value)
    {
        _ = GetViewDefinitions();
${updateViewCases}
    }

    private static bool HasView(IReadOnlyList<GeneratedViewDefinition> views, string componentName)
    {
        foreach (var view in views)
        {
            if (view.ComponentName == componentName)
            {
                return true;
            }
        }

        return false;
    }

    private static void ValidateUniqueViewComponentNames(IReadOnlyList<GeneratedViewDefinition> views)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var view in views)
        {
            if (!seen.Add(view.ComponentName))
            {
                throw new InvalidOperationException($"Duplicate Expo view component name '{view.ComponentName}'.");
            }
        }
    }
}
`;
}

function generateEntryPoints(options: GenerateOptions): string {
  const windowsViewEntryPoints =
    options.platform === 'windows'
      ? `
    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_get_view_last_error",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static unsafe int GetWindowsViewLastError(byte* buffer, int bufferLength)
    {
        try
        {
            return WriteUtf8(GetWindowsViewLastErrorCore(), buffer, bufferLength);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine(ex);
            return -1;
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_get_view_count",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static int GetWindowsViewCount()
    {
        try
        {
            var count = LinkedExpoModulesProvider.GetViewDefinitions().Count;
            ClearWindowsViewLastError();
            return count;
        }
        catch (Exception ex)
        {
            return RecordWindowsViewException(ex);
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_get_view_module_name",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static unsafe int GetWindowsViewModuleName(int viewIndex, byte* buffer, int bufferLength)
    {
        try
        {
            return WriteUtf8(GetViewDefinition(viewIndex).ModuleName, buffer, bufferLength);
        }
        catch (Exception ex)
        {
            return RecordWindowsViewException(ex);
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_get_view_component_name",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static unsafe int GetWindowsViewComponentName(int viewIndex, byte* buffer, int bufferLength)
    {
        try
        {
            return WriteUtf8(GetViewDefinition(viewIndex).ComponentName, buffer, bufferLength);
        }
        catch (Exception ex)
        {
            return RecordWindowsViewException(ex);
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_get_view_prop_count",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static int GetWindowsViewPropCount(int viewIndex)
    {
        try
        {
            return GetViewDefinition(viewIndex).Props.Count;
        }
        catch (Exception ex)
        {
            return RecordWindowsViewException(ex);
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_get_view_prop_name",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static unsafe int GetWindowsViewPropName(int viewIndex, int propIndex, byte* buffer, int bufferLength)
    {
        try
        {
            return WriteUtf8(GetViewPropDefinition(viewIndex, propIndex).Name, buffer, bufferLength);
        }
        catch (Exception ex)
        {
            return RecordWindowsViewException(ex);
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_get_view_prop_kind",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static int GetWindowsViewPropKind(int viewIndex, int propIndex)
    {
        try
        {
            return (int)GetViewPropDefinition(viewIndex, propIndex).Kind;
        }
        catch (Exception ex)
        {
            return RecordWindowsViewException(ex);
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_create_view",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static nint CreateWindowsView(nint runtimeContext, nint componentNameUtf8, int componentNameLength)
    {
        try
        {
            var context = RuntimeContextFromHandle(runtimeContext);
            var componentName = ReadUtf8(componentNameUtf8, componentNameLength);
            var view = LinkedExpoModulesProvider.CreateView(context, componentName);
            return GCHandle.ToIntPtr(GCHandle.Alloc(view));
        }
        catch (Exception ex)
        {
            RecordWindowsViewException(ex);
            return 0;
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_update_string_prop",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static int UpdateWindowsStringProp(
        nint runtimeContext,
        nint viewHandle,
        nint componentNameUtf8,
        int componentNameLength,
        nint propNameUtf8,
        int propNameLength,
        nint valueUtf8,
        int valueLength)
    {
        try
        {
            var context = RuntimeContextFromHandle(runtimeContext);
            var handle = GCHandle.FromIntPtr(viewHandle);
            if (handle.Target is null)
            {
                return -1;
            }

            LinkedExpoModulesProvider.UpdateViewProp(
                context,
                ReadUtf8(componentNameUtf8, componentNameLength),
                handle.Target,
                ReadUtf8(propNameUtf8, propNameLength),
                valueUtf8 == 0 ? null : ReadUtf8(valueUtf8, valueLength));
            return 0;
        }
        catch (Exception ex)
        {
            return RecordWindowsViewException(ex);
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_initialize_composition",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static nint InitializeWindowsComposition(nint viewHandle, nint compositor)
    {
        try
        {
            var view = ViewFromHandle(viewHandle);
            return view.InitializeComposition(compositor);
        }
        catch (Exception ex)
        {
            RecordWindowsViewException(ex);
            return 0;
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_update_layout",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static void UpdateWindowsLayout(nint viewHandle, float width, float height)
    {
        try
        {
            ViewFromHandle(viewHandle).UpdateLayout(width, height);
        }
        catch (Exception ex)
        {
            RecordWindowsViewException(ex);
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_windows_destroy_view",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static void DestroyWindowsView(nint viewHandle)
    {
        if (viewHandle == 0)
        {
            return;
        }

        var handle = GCHandle.FromIntPtr(viewHandle);
        try
        {
            if (handle.Target is Expo.ModulesCore.Windows.WindowsExpoView view)
            {
                view.DisposeComposition();
            }
        }
        catch (Exception ex)
        {
            RecordWindowsViewException(ex);
        }
        finally
        {
            handle.Free();
        }
    }

    private static DotnetRuntimeContext RuntimeContextFromHandle(nint runtimeContext)
    {
        if (runtimeContext == 0)
        {
            throw new ArgumentException("Runtime context handle is null.", nameof(runtimeContext));
        }

        var handle = GCHandle.FromIntPtr(runtimeContext);
        return handle.Target as DotnetRuntimeContext
            ?? throw new InvalidOperationException("Runtime context handle does not target DotnetRuntimeContext.");
    }

    private static Expo.ModulesCore.Windows.WindowsExpoView ViewFromHandle(nint viewHandle)
    {
        if (viewHandle == 0)
        {
            throw new ArgumentException("View handle is null.", nameof(viewHandle));
        }

        var handle = GCHandle.FromIntPtr(viewHandle);
        return handle.Target as Expo.ModulesCore.Windows.WindowsExpoView
            ?? throw new InvalidOperationException("View handle does not target WindowsExpoView.");
    }

    private static unsafe string ReadUtf8(nint utf8, int length)
    {
        if (utf8 == 0 || length == 0)
        {
            return string.Empty;
        }

        return System.Text.Encoding.UTF8.GetString(new ReadOnlySpan<byte>((void*)utf8, length));
    }

    private static GeneratedViewDefinition GetViewDefinition(int viewIndex)
    {
        var views = LinkedExpoModulesProvider.GetViewDefinitions();
        if ((uint)viewIndex >= (uint)views.Count)
        {
            throw new ArgumentOutOfRangeException(nameof(viewIndex));
        }

        return views[viewIndex];
    }

    private static GeneratedViewPropDefinition GetViewPropDefinition(int viewIndex, int propIndex)
    {
        var props = GetViewDefinition(viewIndex).Props;
        if ((uint)propIndex >= (uint)props.Count)
        {
            throw new ArgumentOutOfRangeException(nameof(propIndex));
        }

        return props[propIndex];
    }

    private static unsafe int WriteUtf8(string value, byte* buffer, int bufferLength)
    {
        var byteCount = System.Text.Encoding.UTF8.GetByteCount(value);
        if (buffer is null || bufferLength == 0)
        {
            return byteCount;
        }
        if (bufferLength < byteCount)
        {
            return -1;
        }

        return System.Text.Encoding.UTF8.GetBytes(value, new Span<byte>(buffer, bufferLength));
    }

    private static readonly object WindowsViewLastErrorLock = new();
    private static string WindowsViewLastError = string.Empty;

    private static int RecordWindowsViewException(Exception ex)
    {
        Console.Error.WriteLine(ex);
        lock (WindowsViewLastErrorLock)
        {
            WindowsViewLastError = ex.Message;
        }
        return -1;
    }

    private static void ClearWindowsViewLastError()
    {
        lock (WindowsViewLastErrorLock)
        {
            WindowsViewLastError = string.Empty;
        }
    }

    private static string GetWindowsViewLastErrorCore()
    {
        lock (WindowsViewLastErrorLock)
        {
            return WindowsViewLastError;
        }
    }
`
      : '';

  return `${csharpBanner}
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using Expo.JSI;
using Expo.ModulesCore;

namespace Expo.ModulesCore.Generated;

public static class EntryPoints
{
    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_create_runtime_context",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static nint CreateRuntimeContext(nint api, nint runtimeHandle)
    {
        try
        {
            return CreateRuntimeContextCore(api, runtimeHandle);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine(ex);
            return 0;
        }
    }

    [UnmanagedCallersOnly(
        EntryPoint = "expo_dotnet_teardown_runtime_context",
        CallConvs = new[] { typeof(CallConvCdecl) }
    )]
    public static void TeardownRuntimeContext(nint runtimeContext)
    {
        TeardownRuntimeContextCore(runtimeContext);
    }

    private static nint CreateRuntimeContextCore(nint api, nint runtimeHandle)
    {
        var runtime = JavaScriptRuntime.FromNative(api, runtimeHandle);
        var context = new DotnetRuntimeContext(runtime);
        try
        {
            LinkedExpoModulesProvider.Register(context);
            return GCHandle.ToIntPtr(GCHandle.Alloc(context));
        }
        catch
        {
            context.Dispose();
            throw;
        }
    }

    private static void TeardownRuntimeContextCore(nint runtimeContext)
    {
        if (runtimeContext == 0)
        {
            return;
        }

        var handle = GCHandle.FromIntPtr(runtimeContext);
        if (handle.Target is DotnetRuntimeContext context)
        {
            context.Dispose();
        }

        handle.Free();
    }
${windowsViewEntryPoints}
}
`;
}

function relativePath(from: string, to: string): string {
  return path.relative(from, to).split(path.sep).join('/');
}

function escapeXmlAttribute(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}
