  private static void EmitHostFunction(
      StringBuilder builder,
      ExpoModuleModel module,
      ExpoFunctionModel function,
      SharedObjectHostTarget? shared = null)
  {
    if (!function.IsAsync && function.Parameters.Values.Any(parameter =>
            parameter.PassingKind != ExpoParameterPassingKind.Codec))
    {
      EmitSpanHostFunction(builder, module, function, shared);
      return;
    }

    var hostFunctionName = shared?.HostFunctionName ?? GetHostFunctionName(module, function);
    var label = shared?.Label ?? module.ModuleName;

    builder.AppendLine();
    builder.AppendLine($"  private static global::Expo.JSI.JavaScriptValue {hostFunctionName}(");
    var runtimeParameterName = function.IsAsync ? "jsRuntime" : "runtime";
    // The shared receiver resolves through the codec (registry NativeState identity) before any
    // authored code runs; the local keeps the `module` name so the shared body emission below
    // stays identical for module-level and prototype-level members.
    var targetDeclaration = shared is null
        ? $"var module = ({module.FullyQualifiedTypeName})context;"
        : $"var module = SharedObjectCodec<{shared.ReceiverTypeName}>.Decode(thisValue, {runtimeParameterName}, GeneratedFunction.CurrentRuntimeContext);";
    builder.AppendLine($"      global::Expo.JSI.JavaScriptRuntime {runtimeParameterName},");
    builder.AppendLine("      global::Expo.JSI.JavaScriptValueRef thisValue,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptArguments arguments,");
    builder.AppendLine("      object context)");
    builder.AppendLine("  {");
    var argumentList = string.Join(
        ", ",
        function.Parameters.Values.Select((_, index) => GetParameterLocalName(index))
    );
    var leafArguments = GetLeafArguments(function.Parameters.Values);
    if (function.IsAsync)
    {
      EmitAsyncHostFunctionBody(builder, function, runtimeParameterName, label, targetDeclaration, argumentList, leafArguments);
    }
    else
    {
      builder.AppendLine($"    GeneratedFunction.RequireArgumentCount(\"{EscapeString(label)}.{EscapeString(function.JavaScriptName)}\", arguments, {GetRequiredParameterCount(function)}, {function.Parameters.Values.Count});");
      builder.AppendLine();
      builder.AppendLine($"    {targetDeclaration}");
      EmitLeafReleasingCall(builder, leafArguments, GetLeafResult(function.ReturnCodec), indent =>
      {
        for (var index = 0; index < function.Parameters.Values.Count; index++)
        {
          var parameter = function.Parameters.Values[index];
          builder.AppendLine($"{indent}{GetLocalDeclaration(parameter.Codec, GetParameterLocalName(index), GetParameterExpression(parameter, index, runtimeParameterName))}");
        }

        EmitSyncInvocation(builder, indent, function, $"module.{function.MethodName}({argumentList})");
      });
    }
    builder.AppendLine("  }");
  }

  private static void EmitAsyncHostFunctionBody(
      StringBuilder builder,
      ExpoFunctionModel function,
      string runtimeParameterName,
      string label,
      string targetDeclaration,
      string argumentList,
      IReadOnlyList<LeafValue> leafArguments)
  {
    // Leaf-bearing arguments exist before the outer try, so a failure before CreatePromise returns
    // can release them there. The Promise value is assigned inside the try and returned after it.
    var hasLeafArguments = leafArguments.Count > 0;
    if (hasLeafArguments)
    {
      EmitLeafDeclarations(builder, "    ", leafArguments);
      builder.AppendLine("    global::Expo.JSI.JavaScriptPromiseValue __expoPromiseValue;");
    }
    builder.AppendLine("    try");
    builder.AppendLine("    {");
    builder.AppendLine($"      GeneratedFunction.RequireArgumentCount(\"{EscapeString(label)}.{EscapeString(function.JavaScriptName)}\", arguments, {GetRequiredParameterCount(function)}, {function.Parameters.Values.Count});");
    builder.AppendLine($"      {targetDeclaration}");
    if (function.AsyncResultCodec?.ContextRequirement == ExpoContextRequirement.DotnetRuntimeContext)
    {
      // Capture the exact runtime context while the host-function frame is active; Promise
      // settlement runs after the frame exits and must never read the thread-static accessor.
      builder.AppendLine("      var __expoRuntimeContext = GeneratedFunction.CurrentRuntimeContext;");
    }

    for (var index = 0; index < function.Parameters.Values.Count; index++)
    {
      var parameter = function.Parameters.Values[index];
      builder.AppendLine($"      {GetLocalDeclaration(parameter.Codec, GetParameterLocalName(index), GetParameterExpression(parameter, index, runtimeParameterName))}");
    }

    builder.AppendLine($"      var __expoTask = module.{function.MethodName}({argumentList});");
    builder.AppendLine(hasLeafArguments
        ? $"      __expoPromiseValue = {runtimeParameterName}.CreatePromise("
        : $"      using var __expoPromiseValue = {runtimeParameterName}.CreatePromise(");
    builder.AppendLine("          async _ =>");
    builder.AppendLine("          {");
    if (GetLeafResult(function.AsyncResultCodec) is not null)
    {
      EmitAsyncLeafResultSettlement(builder, function, leafArguments);
    }
    else if (hasLeafArguments)
    {
      // From here the Promise lambda owns the arguments and releases them when the Task finishes.
      builder.AppendLine("            try");
      builder.AppendLine("            {");
      EmitAsyncSettlement(builder, "              ", function);
      builder.AppendLine("            }");
      builder.AppendLine("            finally");
      builder.AppendLine("            {");
      EmitRelease(builder, "              ", leafArguments);
      builder.AppendLine("            }");
    }
    else
    {
      EmitAsyncSettlement(builder, "            ", function);
    }
    builder.AppendLine("          },");
    builder.AppendLine("          createError: GeneratedFunction.CreateJavaScriptError");
    builder.AppendLine("      );");
    if (!hasLeafArguments)
    {
      builder.AppendLine("      return __expoPromiseValue.AsValue();");
    }
    builder.AppendLine("    }");
    builder.AppendLine("    catch (global::System.Exception exception)");
    builder.AppendLine("    {");
    if (hasLeafArguments)
    {
      EmitRelease(builder, "      ", leafArguments);
    }
    builder.AppendLine($"      return GeneratedFunction.CreateRejectedPromise({runtimeParameterName}, exception);");
    builder.AppendLine("    }");
    if (hasLeafArguments)
    {
      // From here the Promise lambda is the sole owner of the arguments; the host frame never
      // touches them again.
      builder.AppendLine("    using (__expoPromiseValue)");
      builder.AppendLine("    {");
      builder.AppendLine("      return __expoPromiseValue.AsValue();");
      builder.AppendLine("    }");
    }
  }

  // Awaits a leaf-free or void result and resolves the Promise with it.
  private static void EmitAsyncSettlement(StringBuilder builder, string indent, ExpoFunctionModel function)
  {
    if (function.AsyncReturnsVoid)
    {
      builder.AppendLine($"{indent}await __expoTask.ConfigureAwait(false);");
      builder.AppendLine($"{indent}return global::Expo.JSI.JavaScriptPromiseResult.Resolve(static runtime => runtime.CreateUndefined());");
      return;
    }

    var asyncEncodeContextArgument = function.AsyncResultCodec!.ContextRequirement == ExpoContextRequirement.DotnetRuntimeContext
        ? ", __expoRuntimeContext"
        : string.Empty;
    builder.AppendLine($"{indent}var __expoResult = await __expoTask.ConfigureAwait(false);");
    builder.AppendLine($"{indent}return global::Expo.JSI.JavaScriptPromiseResult.Resolve(runtime => {function.AsyncResultCodec.Expression}.Encode(__expoResult, runtime{asyncEncodeContextArgument}));");
  }

  // A leaf-bearing result travels with the leaf-bearing arguments in a StrongBox to the Promise
  // result. The factory encodes the result and then releases them, and the abandon callback
  // releases them without encoding. A fault or cancel releases them in the lambda's catch.
  private static void EmitAsyncLeafResultSettlement(
      StringBuilder builder,
      ExpoFunctionModel function,
      IReadOnlyList<LeafValue> leafArguments)
  {
    var resultCodec = function.AsyncResultCodec!;
    var result = new LeafValue(function.AsyncResultType, resultCodec.Expression, "__expoResult");
    LeafValue[] stateValues;
    string stateType;
    string stateValue;
    if (leafArguments.Count == 0)
    {
      // StrongBox<T>.Value is maybe-null, so the scalar form reads it with `!`.
      stateValues = new[] { result with { Value = "__expoState.Value!" } };
      stateType = function.AsyncResultType;
      stateValue = "__expoResult";
    }
    else
    {
      var values = new[] { result }.Concat(leafArguments).ToArray();
      stateValues = values
          .Select((value, index) => value with { Value = $"__expoState.Value.Item{(index + 1).ToString(CultureInfo.InvariantCulture)}" })
          .ToArray();
      stateType = $"({string.Join(", ", values.Select(value => value.TypeName))})";
      stateValue = $"({string.Join(", ", values.Select(value => value.Value))})";
    }

    builder.AppendLine($"            {function.AsyncResultType} __expoResult = default!;");
    builder.AppendLine("            try");
    builder.AppendLine("            {");
    builder.AppendLine("              __expoResult = await __expoTask.ConfigureAwait(false);");
    builder.AppendLine("              return global::Expo.JSI.JavaScriptPromiseResult.ResolveOwned(");
    builder.AppendLine($"                  new global::System.Runtime.CompilerServices.StrongBox<{stateType}>({stateValue}),");
    builder.AppendLine("                  static (runtime, __expoState) =>");
    builder.AppendLine("                  {");
    builder.AppendLine("                    try");
    builder.AppendLine("                    {");
    builder.AppendLine($"                      return {resultCodec.Expression}.Encode({stateValues[0].Value}, runtime);");
    builder.AppendLine("                    }");
    builder.AppendLine("                    finally");
    builder.AppendLine("                    {");
    EmitRelease(builder, "                      ", stateValues);
    builder.AppendLine("                    }");
    builder.AppendLine("                  },");
    builder.AppendLine("                  static __expoState =>");
    builder.AppendLine("                  {");
    EmitRelease(builder, "                    ", stateValues);
    builder.AppendLine("                  }");
    builder.AppendLine("              );");
    builder.AppendLine("            }");
    builder.AppendLine("            catch");
    builder.AppendLine("            {");
    EmitRelease(builder, "              ", new[] { result }.Concat(leafArguments));
    builder.AppendLine("              throw;");
    builder.AppendLine("            }");
  }

  // Calls the authored method and returns its encoded result, inside the host-function frame.
  private static void EmitSyncInvocation(
      StringBuilder builder,
      string indent,
      ExpoFunctionModel function,
      string invocation)
  {
    if (function.ReturnsVoid)
    {
      builder.AppendLine($"{indent}{invocation};");
      builder.AppendLine($"{indent}return runtime.CreateUndefined();");
    }
    else if (function.ReturnPassingKind != ExpoReturnPassingKind.Codec)
    {
      builder.AppendLine($"{indent}return ArrayBufferCodec.EncodeCopy({invocation}, runtime);");
    }
    else
    {
      // The call runs synchronously inside the host-function frame, so the thread-static runtime
      // context is the current one.
      var returnEncodeContextArgument = function.ReturnCodec!.ContextRequirement == ExpoContextRequirement.DotnetRuntimeContext
          ? ", GeneratedFunction.CurrentRuntimeContext"
          : string.Empty;
      EmitEncodedReturn(builder, indent, function.ReturnCodec, invocation, returnEncodeContextArgument);
    }
  }

  // Returns the encoded value. A leaf-bearing value is kept in __expoResult first, so the finally
  // releases it after the encode or after a failure.
  private static void EmitEncodedReturn(
      StringBuilder builder,
      string indent,
      ExpoCodecDescriptor codec,
      string valueExpression,
      string encodeContextArgument)
  {
    if (HoldsLeaves(codec))
    {
      builder.AppendLine($"{indent}__expoResult = {valueExpression};");
      valueExpression = "__expoResult";
    }
    builder.AppendLine($"{indent}return {codec.Expression}.Encode({valueExpression}, runtime{encodeContextArgument});");
  }

  /// <summary>
  /// A leaf-bearing value that generated glue releases: its type with the nullable annotation,
  /// its codec, and the local or expression that holds it.
  /// </summary>
  private sealed record LeafValue(string TypeName, string Codec, string Value);

  // The leaf-bearing codec arguments in declaration order.
  private static IReadOnlyList<LeafValue> GetLeafArguments(IReadOnlyList<ExpoParameterModel> parameters) =>
      parameters
          .Select((parameter, index) => (Parameter: parameter, Index: index))
          .Where(item => item.Parameter.PassingKind == ExpoParameterPassingKind.Codec && HoldsLeaves(item.Parameter.Codec))
          .Select(item => new LeafValue(
              item.Parameter.Codec!.ValueTypeName,
              item.Parameter.Codec.Expression,
              GetParameterLocalName(item.Index)
          ))
          .ToArray();

  private static LeafValue? GetLeafResult(ExpoCodecDescriptor? codec) =>
      HoldsLeaves(codec) ? new LeafValue(codec!.ValueTypeName, codec.Expression, "__expoResult") : null;

  // A leaf-bearing local is declared before the try, so it is only assigned here.
  private static string GetLocalDeclaration(ExpoCodecDescriptor? codec, string local, string expression) =>
      HoldsLeaves(codec) ? $"{local} = {expression};" : $"var {local} = {expression};";

  private static void EmitLeafDeclarations(StringBuilder builder, string indent, IEnumerable<LeafValue> values)
  {
    foreach (var value in values)
    {
      builder.AppendLine($"{indent}{value.TypeName} {value.Value} = default!;");
    }
  }

  // Releases each value through its codec in order, attempting every release before one
  // AggregateException is thrown.
  private static void EmitRelease(StringBuilder builder, string indent, IEnumerable<LeafValue> values)
  {
    builder.AppendLine($"{indent}global::System.Collections.Generic.List<global::System.Exception>? __expoReleaseFailures = null;");
    foreach (var value in values)
    {
      builder.AppendLine($"{indent}CodecRelease.Release<{value.TypeName}, {value.Codec}>({value.Value}, ref __expoReleaseFailures);");
    }
    builder.AppendLine($"{indent}CodecRelease.ThrowIfFailed(__expoReleaseFailures);");
  }

  // Emits the body of a sync host function, property accessor, or shared-object factory. With no
  // leaf-bearing value the body is emitted as is, so leaf-free glue keeps its text. Otherwise the
  // leaf-bearing locals are declared before one try, and its finally releases the result first and
  // then the arguments in declaration order. A value that never decoded is still default and
  // releases nothing.
  private static void EmitLeafReleasingCall(
      StringBuilder builder,
      IReadOnlyList<LeafValue> leafArguments,
      LeafValue? leafResult,
      Action<string> emitBody)
  {
    const string indent = "    ";
    if (leafArguments.Count == 0 && leafResult is null)
    {
      emitBody(indent);
      return;
    }

    EmitLeafDeclarations(builder, indent, leafArguments);
    if (leafResult is not null)
    {
      EmitLeafDeclarations(builder, indent, new[] { leafResult });
    }
    builder.AppendLine($"{indent}try");
    builder.AppendLine($"{indent}{{");
    emitBody(indent + "  ");
    builder.AppendLine($"{indent}}}");
    builder.AppendLine($"{indent}finally");
    builder.AppendLine($"{indent}{{");
    EmitRelease(
        builder,
        indent + "  ",
        leafResult is null ? leafArguments : new[] { leafResult }.Concat(leafArguments)
    );
    builder.AppendLine($"{indent}}}");
  }

  private static void EmitPropertyGetter(
      StringBuilder builder,
      ExpoModuleModel module,
      ExpoPropertyModel property,
      SharedObjectHostTarget? shared = null)
  {
    var getterName = shared?.HostFunctionName ?? GetPropertyGetterFunctionName(module, property);
    var label = shared?.Label ?? module.ModuleName;
    var targetDeclaration = shared is null
        ? $"var module = ({module.FullyQualifiedTypeName})context;"
        : $"var module = SharedObjectCodec<{shared.ReceiverTypeName}>.Decode(thisValue, runtime, GeneratedFunction.CurrentRuntimeContext);";
    var encodeContextArgument = property.Codec.ContextRequirement == ExpoContextRequirement.DotnetRuntimeContext
        ? ", GeneratedFunction.CurrentRuntimeContext"
        : string.Empty;

    builder.AppendLine();
    builder.AppendLine($"  private static global::Expo.JSI.JavaScriptValue {getterName}(");
    builder.AppendLine("      global::Expo.JSI.JavaScriptRuntime runtime,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptValueRef thisValue,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptArguments arguments,");
    builder.AppendLine("      object context)");
    builder.AppendLine("  {");
    builder.AppendLine($"    GeneratedFunction.RequireArgumentCount(\"{EscapeString(label)}.{EscapeString(property.JavaScriptName)}\", arguments, 0);");
    builder.AppendLine($"    {targetDeclaration}");
    EmitLeafReleasingCall(
        builder,
        Array.Empty<LeafValue>(),
        GetLeafResult(property.Codec),
        indent => EmitEncodedReturn(builder, indent, property.Codec, $"module.{property.PropertyName}", encodeContextArgument)
    );
    builder.AppendLine("  }");
  }

  private static void EmitPropertySetter(
      StringBuilder builder,
      ExpoModuleModel module,
      ExpoPropertyModel property,
      SharedObjectHostTarget? shared = null)
  {
    var setterName = shared?.HostFunctionName ?? GetPropertySetterFunctionName(module, property);
    var label = shared?.Label ?? module.ModuleName;
    var targetDeclaration = shared is null
        ? $"var module = ({module.FullyQualifiedTypeName})context;"
        : $"var module = SharedObjectCodec<{shared.ReceiverTypeName}>.Decode(thisValue, runtime, GeneratedFunction.CurrentRuntimeContext);";

    builder.AppendLine();
    builder.AppendLine($"  private static global::Expo.JSI.JavaScriptValue {setterName}(");
    builder.AppendLine("      global::Expo.JSI.JavaScriptRuntime runtime,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptValueRef thisValue,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptArguments arguments,");
    builder.AppendLine("      object context)");
    builder.AppendLine("  {");
    builder.AppendLine($"    GeneratedFunction.RequireArgumentCount(\"{EscapeString(label)}.{EscapeString(property.JavaScriptName)}\", arguments, 1);");
    builder.AppendLine($"    {targetDeclaration}");
    var leafValues = HoldsLeaves(property.Codec)
        ? new[] { new LeafValue(property.Codec.ValueTypeName, property.Codec.Expression, "__expoValue") }
        : Array.Empty<LeafValue>();
    EmitLeafReleasingCall(builder, leafValues, null, indent =>
    {
      builder.AppendLine($"{indent}{GetLocalDeclaration(property.Codec, "__expoValue", GetDecodeExpression(property.Codec, 0, "runtime"))}");
      builder.AppendLine($"{indent}module.{property.PropertyName} = __expoValue;");
      builder.AppendLine($"{indent}return runtime.CreateUndefined();");
    });
    builder.AppendLine("  }");
  }

  private static void EmitSpanHostFunction(
      StringBuilder builder,
      ExpoModuleModel module,
      ExpoFunctionModel function,
      SharedObjectHostTarget? shared = null)
  {
    var spanHostFunctionName = shared?.HostFunctionName ?? GetHostFunctionName(module, function);
    var spanLabel = shared?.Label ?? module.ModuleName;
    var spanTargetDeclaration = shared is null
        ? $"var module = ({module.FullyQualifiedTypeName})context;"
        : $"var module = SharedObjectCodec<{shared.ReceiverTypeName}>.Decode(thisValue, runtime, GeneratedFunction.CurrentRuntimeContext);";
    var spanParameter = function.Parameters.Values.Single(parameter =>
        parameter.PassingKind != ExpoParameterPassingKind.Codec);
    var spanIndex = Enumerable.Range(0, function.Parameters.Values.Count)
        .Single(index => ReferenceEquals(function.Parameters.Values[index], spanParameter));
    var spanBuffer = $"__expoSpanBuffer{spanIndex}";
    var spanMethod = spanParameter.PassingKind == ExpoParameterPassingKind.MutableByteSpan
        ? "WithBytes"
        : "WithReadOnlyBytes";

    builder.AppendLine();
    builder.AppendLine($"  private static global::Expo.JSI.JavaScriptValue {spanHostFunctionName}(");
    builder.AppendLine("      global::Expo.JSI.JavaScriptRuntime runtime,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptValueRef thisValue,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptArguments arguments,");
    builder.AppendLine("      object context)");
    builder.AppendLine("  {");
    builder.AppendLine($"    GeneratedFunction.RequireArgumentCount(\"{EscapeString(spanLabel)}.{EscapeString(function.JavaScriptName)}\", arguments, {GetRequiredParameterCount(function)}, {function.Parameters.Values.Count});");
    builder.AppendLine($"    {spanTargetDeclaration}");
    var argumentList = string.Join(", ", function.Parameters.Values.Select((_, index) => GetParameterLocalName(index)));
    // One try around WithBytes releases the leaf-bearing arguments and result. The span lease
    // keeps its own using, because it must outlive the whole WithBytes call.
    EmitLeafReleasingCall(builder, GetLeafArguments(function.Parameters.Values), GetLeafResult(function.ReturnCodec), indent =>
    {
      for (var index = 0; index < function.Parameters.Values.Count; index++)
      {
        var parameter = function.Parameters.Values[index];
        if (parameter.PassingKind != ExpoParameterPassingKind.Codec)
        {
          continue;
        }
        builder.AppendLine($"{indent}{GetLocalDeclaration(parameter.Codec, GetParameterLocalName(index), GetParameterExpression(parameter, index, "runtime"))}");
      }
      builder.AppendLine($"{indent}using var {spanBuffer} = ArrayBufferCodec.Decode(arguments.GetValue({spanIndex}), runtime);");
      builder.AppendLine($"{indent}return {spanBuffer}.{spanMethod}(__expoArg{spanIndex} =>");
      builder.AppendLine($"{indent}{{");
      EmitSyncInvocation(builder, indent + "  ", function, $"module.{function.MethodName}({argumentList})");
      builder.AppendLine($"{indent}}});");
    });
    builder.AppendLine("  }");
  }

  private static void EmitObservingHookFunction(
      StringBuilder builder,
      ExpoModuleModel module,
      string javaScriptName,
      IReadOnlyList<ExpoObservingHookModel> hooks)
  {
    builder.AppendLine();
    builder.AppendLine($"  private static global::Expo.JSI.JavaScriptValue {GetObservingHookFunctionName(module, javaScriptName)}(");
    builder.AppendLine("      global::Expo.JSI.JavaScriptRuntime runtime,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptValueRef thisValue,");
    builder.AppendLine("      global::Expo.JSI.JavaScriptArguments arguments,");
    builder.AppendLine("      object context)");
    builder.AppendLine("  {");
    builder.AppendLine($"    GeneratedFunction.RequireArgumentCount(\"{EscapeString(module.ModuleName)}.{javaScriptName}\", arguments, 1);");
    builder.AppendLine();
    builder.AppendLine($"    var module = ({module.FullyQualifiedTypeName})context;");
    builder.AppendLine("    var __expoEventName = StringCodec.Decode(arguments.GetValue(0), runtime);");
    foreach (var hook in hooks)
    {
      if (hook.EventName is not null)
      {
        builder.AppendLine($"    if (__expoEventName == \"{EscapeString(hook.EventName)}\")");
        builder.AppendLine("    {");
        builder.AppendLine($"      module.{hook.MethodName}();");
        builder.AppendLine("    }");
      }
      else
      {
        builder.AppendLine($"    module.{hook.MethodName}(__expoEventName);");
      }
    }
    builder.AppendLine("    return runtime.CreateUndefined();");
    builder.AppendLine("  }");
  }

  // One emitter for every record codec. A record that holds leaves also gets Release, and its
  // Decode releases the leaf fields it already decoded when a later field fails. Encode never
  // disposes a field of the record, so every record keeps the same Encode text.
  private static void EmitRecordCodec(StringBuilder builder, ExpoGeneratedRecordCodecModel codec)
  {
    var leafFieldModels = codec.Fields.Values.Where(field => HoldsLeaves(field.Codec)).ToArray();
    var leafFields = leafFieldModels
        .Select(field => new LeafValue(field.Codec.ValueTypeName, field.Codec.Expression, GetRecordFieldLocalName(field)))
        .ToArray();

    builder.AppendLine($"  private readonly struct {codec.CodecTypeName} : global::Expo.ModulesCore.Codecs.IJavaScriptCodec<{codec.RecordTypeName}>");
    builder.AppendLine("  {");
    builder.AppendLine($"    public static {codec.RecordTypeName} Decode(global::Expo.JSI.JavaScriptValueRef value, global::Expo.JSI.JavaScriptRuntime runtime)");
    builder.AppendLine("    {");
    builder.AppendLine("      var obj = value.AsObject();");
    EmitRecordDecodeBody(builder, codec, leafFields, indent =>
    {
      foreach (var field in codec.Fields.Values)
      {
        var read = $"obj.GetProperty(\"{EscapeString(field.JavaScriptName)}\")";
        if (field.Kind == ExpoRecordFieldKind.OptionalByType)
        {
          builder.AppendLine($"{indent}{GetLocalDeclaration(field.Codec, GetRecordFieldLocalName(field), $"{field.Codec.Expression}.Decode({read}, runtime)")}");
          continue;
        }

        builder.AppendLine($"{indent}var {GetRecordFieldPropertyLocalName(field)} = {read};");
        EmitRecordFieldDecode(builder, indent, field);
      }
    });
    builder.AppendLine("    }");
    builder.AppendLine();
    builder.AppendLine($"    public static {codec.RecordTypeName} Decode(global::Expo.JSI.JavaScriptValue value, global::Expo.JSI.JavaScriptRuntime runtime)");
    builder.AppendLine("    {");
    builder.AppendLine("      using var obj = value.AsObject();");
    EmitRecordDecodeBody(builder, codec, leafFields, indent =>
    {
      foreach (var field in codec.Fields.Values)
      {
        builder.AppendLine($"{indent}using var {GetRecordFieldPropertyLocalName(field)} = obj.GetProperty(\"{EscapeString(field.JavaScriptName)}\");");
        EmitRecordFieldDecode(builder, indent, field);
      }
    });
    builder.AppendLine("    }");
    builder.AppendLine();
    builder.AppendLine($"    public static global::Expo.JSI.JavaScriptValue Encode({codec.RecordTypeName} value, global::Expo.JSI.JavaScriptRuntime runtime)");
    builder.AppendLine("    {");
    builder.AppendLine("      using var obj = runtime.CreateObject();");
    foreach (var field in codec.Fields.Values)
    {
      builder.AppendLine($"      using var {GetRecordFieldLocalName(field)} = {field.Codec.Expression}.Encode(value.{field.CSharpPropertyName}, runtime);");
      builder.AppendLine($"      obj.SetProperty(\"{EscapeString(field.JavaScriptName)}\", {GetRecordFieldLocalName(field)});");
    }
    builder.AppendLine("      return obj.AsValue();");
    builder.AppendLine("    }");
    if (leafFields.Length > 0)
    {
      // A class record can be null inside a collection, so Release skips it and the collection
      // still releases its other elements.
      builder.AppendLine();
      builder.AppendLine($"    public static void Release({codec.RecordTypeName} value)");
      builder.AppendLine("    {");
      if (!codec.IsValueType)
      {
        builder.AppendLine("      if (value is null) return;");
      }
      EmitRelease(
          builder,
          "      ",
          leafFieldModels.Select(field =>
              new LeafValue(field.Codec.ValueTypeName, field.Codec.Expression, $"value.{field.CSharpPropertyName}"))
      );
      builder.AppendLine("    }");
    }
    builder.AppendLine("  }");
    builder.AppendLine();
  }

  private static string GetUnionKindCondition(ExpoGeneratedUnionCaseModel unionCase)
  {
    var kinds = Enum.GetValues(typeof(ExpoJavaScriptKinds))
        .Cast<ExpoJavaScriptKinds>()
        .Where(kind => kind is not (ExpoJavaScriptKinds.None or ExpoJavaScriptKinds.All) && (unionCase.Kinds & kind) == kind)
        .Select(kind => $"__expoKind == global::Expo.JSI.JavaScriptValueKind.{kind}");
    var condition = string.Join(" || ", kinds);
    return unionCase.IntegerGate.Length == 0 ? condition : $"{condition} && {unionCase.IntegerGate}";
  }

  // One emitter for every union codec: a fixed sequence of typed payload-codec calls, with no
  // reflection and no object-typed values. Decode visits the cases in declaration order and skips a
  // case whose kinds do not contain the value kind. An attempt lets an AggregateException (a release
  // failure) propagate and treats any other exception as a failed attempt. Case construction runs
  // outside the attempt, so a throwing constructor never falls through to a later case.
  private static void EmitUnionCodec(StringBuilder builder, ExpoGeneratedUnionCodecModel codec)
  {
    var cases = codec.Cases.Values;
    var unionTypeName = codec.UnionTypeName;

    builder.AppendLine($"  private readonly struct {codec.CodecTypeName} : global::Expo.ModulesCore.Codecs.IJavaScriptCodec<{unionTypeName}>");
    builder.AppendLine("  {");
    builder.AppendLine($"    public static {unionTypeName} Decode(global::Expo.JSI.JavaScriptValueRef value, global::Expo.JSI.JavaScriptRuntime runtime)");
    builder.AppendLine("    {");
    builder.AppendLine("      var __expoKind = value.Kind;");
    if (cases.Any(unionCase => unionCase.IntegerGate.Length > 0))
    {
      builder.AppendLine("      var __expoNumber = __expoKind == global::Expo.JSI.JavaScriptValueKind.Number ? value.AsDouble() : 0d;");
    }
    builder.AppendLine("      global::System.Exception? __expoFailure = null;");
    for (var index = 0; index < cases.Count; index++)
    {
      var unionCase = cases[index];
      var payload = $"__expoPayload{index}";
      var decoded = $"__expoDecoded{index}";
      if (unionCase.Kinds != ExpoJavaScriptKinds.All || unionCase.IntegerGate.Length > 0)
      {
        builder.AppendLine($"      if ({GetUnionKindCondition(unionCase)})");
      }
      builder.AppendLine("      {");
      builder.AppendLine($"        var {decoded} = false;");
      builder.AppendLine($"        {unionCase.PayloadCodec.ValueTypeName} {payload} = default!;");
      builder.AppendLine("        try");
      builder.AppendLine("        {");
      builder.AppendLine($"          {payload} = {unionCase.PayloadCodec.Expression}.Decode(value, runtime);");
      builder.AppendLine($"          {decoded} = true;");
      builder.AppendLine("        }");
      builder.AppendLine("        catch (global::System.AggregateException)");
      builder.AppendLine("        {");
      builder.AppendLine("          throw;");
      builder.AppendLine("        }");
      builder.AppendLine("        catch (global::System.Exception __expoAttemptFailure)");
      builder.AppendLine("        {");
      builder.AppendLine("          __expoFailure = __expoAttemptFailure;");
      builder.AppendLine("        }");
      builder.AppendLine($"        if ({decoded})");
      builder.AppendLine("        {");
      if (HoldsLeaves(unionCase.PayloadCodec))
      {
        builder.AppendLine("          try");
        builder.AppendLine("          {");
        builder.AppendLine($"            return new {unionCase.CaseTypeName}({payload});");
        builder.AppendLine("          }");
        builder.AppendLine("          catch");
        builder.AppendLine("          {");
        EmitRelease(
            builder,
            "            ",
            new[] { new LeafValue(unionCase.PayloadCodec.ValueTypeName, unionCase.PayloadCodec.Expression, payload) });
        builder.AppendLine("            throw;");
        builder.AppendLine("          }");
      }
      else
      {
        builder.AppendLine($"          return new {unionCase.CaseTypeName}({payload});");
      }
      builder.AppendLine("        }");
      builder.AppendLine("      }");
    }
    var expected = string.Join(", ", cases.Select(unionCase => $"\"{EscapeString(unionCase.PayloadMessageName)}\""));
    builder.AppendLine($"      throw new global::Expo.ModulesCore.UnionCaseMismatchException(\"{EscapeString(codec.UnionName)}\", new[] {{ {expected} }}, __expoKind, __expoFailure);");
    builder.AppendLine("    }");
    builder.AppendLine();
    builder.AppendLine($"    public static {unionTypeName} Decode(global::Expo.JSI.JavaScriptValue value, global::Expo.JSI.JavaScriptRuntime runtime) =>");
    builder.AppendLine("        Decode(value.Ref, runtime);");
    builder.AppendLine();
    builder.AppendLine($"    public static global::Expo.JSI.JavaScriptValue Encode({unionTypeName} value, global::Expo.JSI.JavaScriptRuntime runtime)");
    builder.AppendLine("    {");
    builder.AppendLine("      global::System.ArgumentNullException.ThrowIfNull(value);");
    builder.AppendLine("      return value switch");
    builder.AppendLine("      {");
    for (var index = 0; index < cases.Count; index++)
    {
      var unionCase = cases[index];
      builder.AppendLine($"        {unionCase.CaseTypeName} __expoCase{index} => {unionCase.PayloadCodec.Expression}.Encode(__expoCase{index}.{unionCase.PayloadPropertyName}, runtime),");
    }
    var notACaseName = unionTypeName.StartsWith("global::", StringComparison.Ordinal) ? unionTypeName.Substring("global::".Length) : unionTypeName;
    builder.AppendLine($"        _ => throw global::Expo.ModulesCore.Codecs.UnionCodecErrors.NotACase(value, \"{EscapeString(notACaseName)}\"),");
    builder.AppendLine("      };");
    builder.AppendLine("    }");
    if (codec.ResourceOwnership == ExpoResourceOwnership.HoldsLeaves)
    {
      builder.AppendLine();
      builder.AppendLine($"    public static void Release({unionTypeName} value)");
      builder.AppendLine("    {");
      builder.AppendLine("      switch (value)");
      builder.AppendLine("      {");
      for (var index = 0; index < cases.Count; index++)
      {
        var unionCase = cases[index];
        if (!HoldsLeaves(unionCase.PayloadCodec))
        {
          continue;
        }

        builder.AppendLine($"        case {unionCase.CaseTypeName} __expoCase{index}:");
        builder.AppendLine("        {");
        EmitRelease(
            builder,
            "          ",
            new[]
            {
                new LeafValue(
                    unionCase.PayloadCodec.ValueTypeName,
                    unionCase.PayloadCodec.Expression,
                    $"__expoCase{index}.{unionCase.PayloadPropertyName}"),
            });
        builder.AppendLine("          return;");
        builder.AppendLine("        }");
      }
      builder.AppendLine("      }");
      builder.AppendLine("    }");
    }
    builder.AppendLine("  }");
    builder.AppendLine();
  }

  // Emits the field decodes and the record construction. With leaf fields, they are declared
  // before a try whose catch releases the ones already decoded and rethrows.
  // One emitter for every string enum codec: two constant switches, so the codec needs no
  // reflection and no runtime context, and holds no leaves (the default Release). The decode error
  // lists the declared strings in declaration order; the encode error renders the underlying number
  // with the invariant culture, so the error path reads no enum metadata either.
  private static void EmitEnumCodec(StringBuilder builder, ExpoGeneratedEnumCodecModel codec)
  {
    var enumTypeName = codec.EnumTypeName;
    var displayName = enumTypeName.StartsWith("global::", StringComparison.Ordinal)
        ? enumTypeName.Substring("global::".Length)
        : enumTypeName;
    var members = codec.Members.Values;
    var accepted = string.Join(", ", members.Select(member => $"'{member.JavaScriptName}'"));

    builder.AppendLine($"  private readonly struct {codec.CodecTypeName} : global::Expo.ModulesCore.Codecs.IJavaScriptCodec<{enumTypeName}>");
    builder.AppendLine("  {");
    builder.AppendLine($"    public static {enumTypeName} Decode(global::Expo.JSI.JavaScriptValueRef value, global::Expo.JSI.JavaScriptRuntime runtime) => FromJavaScriptString(value.AsString());");
    builder.AppendLine();
    builder.AppendLine($"    public static {enumTypeName} Decode(global::Expo.JSI.JavaScriptValue value, global::Expo.JSI.JavaScriptRuntime runtime) => FromJavaScriptString(value.AsString());");
    builder.AppendLine();
    builder.AppendLine($"    public static global::Expo.JSI.JavaScriptValue Encode({enumTypeName} value, global::Expo.JSI.JavaScriptRuntime runtime) => runtime.CreateString(ToJavaScriptString(value));");
    builder.AppendLine();
    builder.AppendLine($"    private static {enumTypeName} FromJavaScriptString(string value) => value switch");
    builder.AppendLine("    {");
    foreach (var member in members)
    {
      builder.AppendLine($"      \"{EscapeString(member.JavaScriptName)}\" => {enumTypeName}.{EscapeIdentifier(member.CSharpName)},");
    }
    builder.AppendLine($"      _ => throw new global::System.ArgumentException(\"'\" + value + \"' is not a valid {EscapeString(displayName)} value. It must be one of: {EscapeString(accepted)}\"),");
    builder.AppendLine("    };");
    builder.AppendLine();
    builder.AppendLine($"    private static string ToJavaScriptString({enumTypeName} value) => value switch");
    builder.AppendLine("    {");
    foreach (var member in members)
    {
      builder.AppendLine($"      {enumTypeName}.{EscapeIdentifier(member.CSharpName)} => \"{EscapeString(member.JavaScriptName)}\",");
    }
    builder.AppendLine($"      _ => throw new global::System.InvalidOperationException((({codec.UnderlyingTypeName})value).ToString(global::System.Globalization.CultureInfo.InvariantCulture) + \" is not a member of {EscapeString(displayName)}, so it has no JavaScript value.\"),");
    builder.AppendLine("    };");
    builder.AppendLine("  }");
    builder.AppendLine();
  }

  private static void EmitRecordDecodeBody(
      StringBuilder builder,
      ExpoGeneratedRecordCodecModel codec,
      IReadOnlyList<LeafValue> leafFields,
      Action<string> emitFieldDecodes)
  {
    var construction = $"return new {codec.RecordTypeName}({string.Join(", ", codec.Fields.Values.Select(GetRecordFieldLocalName))});";
    if (leafFields.Count == 0)
    {
      emitFieldDecodes("      ");
      builder.AppendLine($"      {construction}");
      return;
    }

    EmitLeafDeclarations(builder, "      ", leafFields);
    builder.AppendLine("      try");
    builder.AppendLine("      {");
    emitFieldDecodes("        ");
    builder.AppendLine($"        {construction}");
    builder.AppendLine("      }");
    builder.AppendLine("      catch");
    builder.AppendLine("      {");
    EmitRelease(builder, "        ", leafFields);
    builder.AppendLine("        throw;");
    builder.AppendLine("      }");
  }

  private static string SanitizeIdentifier(string value)
  {
    var builder = new StringBuilder(value.Length);
    foreach (var character in value)
    {
      builder.Append(char.IsLetterOrDigit(character) ? character : '_');
    }
    return builder.Length == 0 ? "ExpoModules" : builder.ToString();
  }

  private static string GetHostFunctionName(ExpoModuleModel module, ExpoFunctionModel function) =>
      $"{SanitizeIdentifier(module.ModuleName)}_{SanitizeIdentifier(function.JavaScriptName)}_HostFunction";

  private static string GetPropertyGetterFunctionName(ExpoModuleModel module, ExpoPropertyModel property) =>
      $"{SanitizeIdentifier(module.ModuleName)}_{SanitizeIdentifier(property.PropertyName)}_Getter";

  private static string GetPropertySetterFunctionName(ExpoModuleModel module, ExpoPropertyModel property) =>
      $"{SanitizeIdentifier(module.ModuleName)}_{SanitizeIdentifier(property.PropertyName)}_Setter";

  private static string GetModuleRegistrationFunctionName(ExpoModuleModel module) =>
      $"Register{SanitizeIdentifier(module.ModuleName)}";

  private static string GetObservingHookFunctionName(ExpoModuleModel module, string javaScriptName) =>
      $"{SanitizeIdentifier(module.ModuleName)}_{SanitizeIdentifier(javaScriptName)}_HostFunction";

  private static string GetRecordFieldLocalName(ExpoGeneratedRecordFieldModel field) =>
      field.ParameterName == "value" ? "__expoValue" : field.ParameterName;

  // Decodes one record field from its property local, read once. A required field throws a named
  // ArgumentException for JavaScript undefined before the codec runs; a defaulted field yields its
  // inlined default without calling the codec. Explicit null and every other value go to the
  // field codec.
  private static void EmitRecordFieldDecode(
      StringBuilder builder,
      string indent,
      ExpoGeneratedRecordFieldModel field)
  {
    var propertyLocal = GetRecordFieldPropertyLocalName(field);
    var decode = $"{field.Codec.Expression}.Decode({propertyLocal}, runtime)";
    var undefinedCheck = $"{propertyLocal}.Kind == global::Expo.JSI.JavaScriptValueKind.Undefined";
    if (field.Kind == ExpoRecordFieldKind.Required)
    {
      // Thrown inside the decode try, so leaves of earlier fields are released by its catch.
      builder.AppendLine($"{indent}if ({undefinedCheck}) throw new global::System.ArgumentException(\"Value for property '{EscapeString(field.JavaScriptName)}' is required, got undefined\");");
    }
    else if (field.Kind == ExpoRecordFieldKind.Defaulted)
    {
      decode = $"{undefinedCheck} ? {field.DefaultValueExpression} : {decode}";
    }

    builder.AppendLine($"{indent}{GetLocalDeclaration(field.Codec, GetRecordFieldLocalName(field), decode)}");
  }

  // The owned overload already names this local `<field>Value`; the borrowed overload uses the
  // same name, so an OptionalByType field keeps today's text in both.
  private static string GetRecordFieldPropertyLocalName(ExpoGeneratedRecordFieldModel field) =>
      $"{field.ParameterName}Value";

  private static int GetRequiredParameterCount(ExpoFunctionModel function) =>
      function.Parameters.Values.Count(parameter => !parameter.HasDefaultValue);

  private static string GetParameterLocalName(int index) =>
      $"__expoArg{index.ToString(CultureInfo.InvariantCulture)}";

